package com.CompanyQuestions.MyHashMap;

public class ListNode {
    public int key;
    public int value;
    public ListNode next;

    public ListNode() {
        this.key = -1;
        this.value = -1;
        this.next = null;
    }

    public ListNode(int key, int value) {
        this.key = key;
        this.value = value;
        this.next = null;
    }
}
